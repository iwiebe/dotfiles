#!/usr/bin/env bash
#
# Interactive bootstrap for rsync-over-ssh backups of Docker volumes
# (written for Rocky Linux / RHEL, run as root).
#
# It asks for the ssh key, source dir, remote target and schedule, writes
# /usr/local/bin/backup-<hostname>-docker-volumes.sh, installs a cron entry
# and fires a test run. Safe to re-run: the script is regenerated and the
# cron entry replaced rather than duplicated.
#
#   sudo ./docker-volume-backup-bootstrap.sh
#   curl -fsSL <raw url> | sudo bash        # prompts read from the terminal
#
set -euo pipefail

if [[ $EUID -ne 0 ]]; then
  echo "This needs to run as root (try: sudo $0)" >&2
  exit 1
fi

if ! { : </dev/tty; } 2>/dev/null; then
  echo "No terminal available for prompts." >&2
  exit 1
fi

missing=()
for cmd in rsync ssh crontab flock; do
  command -v "$cmd" >/dev/null 2>&1 || missing+=("$cmd")
done
if ((${#missing[@]})); then
  echo "Missing: ${missing[*]}" >&2
  echo "Install with: dnf install -y rsync openssh-clients cronie util-linux" >&2
  exit 1
fi

HOST=$(hostname -s)

ask() { # ask "Prompt" "default"  -> echoes the answer
  local reply
  read -r -p "$1 [$2]: " reply </dev/tty
  printf '%s' "${reply:-$2}"
}

echo "Docker volume backup bootstrap for host: $HOST"
echo

# --- prompts -----------------------------------------------------------------
key_in=$(ask "SSH key (name in /root/.ssh, or full path)" "id_ed25519")
[[ $key_in == */* ]] && SSH_KEY=$key_in || SSH_KEY=/root/.ssh/$key_in
if [[ ! -r $SSH_KEY ]]; then
  echo "SSH key not found or unreadable: $SSH_KEY" >&2
  exit 1
fi

SOURCE=$(ask "Source directory" "/var/lib/docker/volumes/")
SOURCE="${SOURCE%/}/"   # trailing slash: copy contents, not the directory itself
if [[ ! -d $SOURCE ]]; then
  echo "Source directory does not exist: $SOURCE" >&2
  exit 1
fi

REMOTE=$(ask "Remote user@host" "rsync@192.168.1.210")
TARGET=$(ask "Remote target directory" "/mnt/nicomekl/backups")
TARGET="${TARGET%/}"
EXCLUDE=$(ask "Exclude pattern" "*_db*/")
SCHEDULE=$(ask "Cron schedule" "15 2 * * *")

BACKUP_SCRIPT="/usr/local/bin/backup-${HOST}-docker-volumes.sh"
LOGFILE="/var/log/backup-${HOST}-docker-volumes.log"

echo
echo "  host:      $HOST"
echo "  ssh key:   $SSH_KEY"
echo "  source:    $SOURCE"
echo "  dest:      $REMOTE:$TARGET/${HOST}-docker-volumes-<timestamp>/"
echo "  exclude:   $EXCLUDE"
echo "  schedule:  $SCHEDULE"
echo "  script:    $BACKUP_SCRIPT"
echo "  log:       $LOGFILE"
echo
[[ $(ask "Proceed?" "Y") =~ ^[Yy] ]] || { echo "Aborted."; exit 0; }

# --- preflight: can we reach the target? ---------------------------------------
SSH_OPTS=(-i "$SSH_KEY" -o BatchMode=yes -o StrictHostKeyChecking=accept-new -o ConnectTimeout=10)
echo
echo "==> Checking ssh access and target directory..."
if ssh "${SSH_OPTS[@]}" "$REMOTE" "test -d $(printf '%q' "$TARGET")"; then
  echo "OK"
else
  echo "Could not ssh to $REMOTE with $SSH_KEY, or $TARGET doesn't exist there." >&2
  [[ $(ask "Continue anyway?" "n") =~ ^[Yy] ]] || exit 1
fi

# --- generate the backup script ------------------------------------------------
echo "==> Writing $BACKUP_SCRIPT"
{
  echo '#!/bin/bash'
  echo "# Generated by docker-volume-backup-bootstrap.sh on $(date -Is). Re-run the bootstrap to regenerate."
  echo 'set -euo pipefail'
  echo
  printf 'HOST=%q\n'    "$HOST"
  printf 'SSH_KEY=%q\n' "$SSH_KEY"
  printf 'SOURCE=%q\n'  "$SOURCE"
  printf 'REMOTE=%q\n'  "$REMOTE"
  printf 'TARGET=%q\n'  "$TARGET"
  printf 'EXCLUDE=%q\n' "$EXCLUDE"
  printf 'LOGFILE=%q\n' "$LOGFILE"
  printf 'LOCKFILE=%q\n' "/var/lock/backup-${HOST}-docker-volumes.lock"
  cat <<'BODY'

STAMP=$(date +%Y-%m-%d_%H-%M-%S)

# Prevent overlapping runs
exec 9>"$LOCKFILE"
if ! flock -n 9; then
  echo "$(date): previous run still going, exiting" >> "$LOGFILE"
  exit 1
fi

rc=0
{
  echo "=== $(date) start ==="
  /usr/bin/rsync -az --stats \
    -e "ssh -i $SSH_KEY -o BatchMode=yes -o StrictHostKeyChecking=accept-new" \
    --exclude="$EXCLUDE" \
    "$SOURCE" \
    "${REMOTE}:${TARGET}/${HOST}-docker-volumes-${STAMP}/" || rc=$?
  echo "=== $(date) finished, exit code $rc ==="
} >> "$LOGFILE" 2>&1
exit "$rc"
BODY
} > "$BACKUP_SCRIPT"

chown root:root "$BACKUP_SCRIPT"
chmod 700 "$BACKUP_SCRIPT"
touch "$LOGFILE"
chmod 600 "$LOGFILE"

# --- cron ------------------------------------------------------------------------
echo "==> Installing cron entry"
{
  { crontab -l 2>/dev/null || true; } | grep -vF "$BACKUP_SCRIPT" || true
  echo "# docker volume backup: $BACKUP_SCRIPT"
  echo "$SCHEDULE $BACKUP_SCRIPT"
} | crontab -
systemctl enable --now crond >/dev/null 2>&1 || true
crontab -l | grep -F "$BACKUP_SCRIPT"

# --- test run --------------------------------------------------------------------
echo
if [[ $(ask "Run a test backup now? (a first run copies everything, so it can take a while)" "Y") =~ ^[Yy] ]]; then
  echo "==> Running $BACKUP_SCRIPT"
  rc=0
  "$BACKUP_SCRIPT" || rc=$?
  echo
  tail -n 25 "$LOGFILE"
  echo
  if ((rc == 0)); then
    echo "Test run succeeded."
  else
    echo "Test run FAILED (exit code $rc). See $LOGFILE" >&2
    exit "$rc"
  fi
fi

echo "Done. Next scheduled run: $SCHEDULE. Log: $LOGFILE"
